"""Score every run in runs/ on the test sets and write docs/results/test_sets.md.

A run is any folder with `pred.npz` + `meta.json` (written by the trainers and by
scripts/benchmark/vlm.py / laya_textonly.py). For each run, temperatures are fitted on the
calibration split, then every test set is scored: Nutrition5k, its never-seen-meals subset,
DFood-TJ and NutritionVerse-Real. Seeds of one configuration (`<name>_s<N>`) are averaged.

Columns: kcal MAE (mean absolute error, kcal) and r (correlation) for calories; F1 ±1 is the
macro F1 over the 18 bins counting a neighbouring bin as correct, averaged over the five
targets; ECE is the calibration error; "cov 80" is how often the 80 % range contains the
true value (should be ≈ 0.80). Metric definitions: docs/results.md.

    uv run python scripts/benchmark/evaluate.py
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path
from typing import Any

import numpy as np

from layamacro.eval.evaluate import evaluate_run

SETS = {
    "nutrition5k": "Nutrition5k",
    "nutrition5k_novel": "N5k never-seen meals",
    "dfood_tj": "DFood-TJ",
    "nutritionverse_real": "NutritionVerse-Real",
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=Path, default=Path("runs"))
    ap.add_argument("--out", type=Path, default=Path("docs/results/test_sets.md"))
    args = ap.parse_args()

    groups: dict[str, list[dict[str, Any]]] = {}
    for run in sorted(p.parent for p in args.runs.glob("*/pred.npz")):
        res = evaluate_run(run)
        groups.setdefault(re.sub(r"_s\d+$", "", run.name), []).append(res)
        print(f"scored {run.name}", flush=True)
    (args.out.parent).mkdir(parents=True, exist_ok=True)
    (args.out.with_suffix(".json")).write_text(
        json.dumps({g: [r["results"] for r in rs] for g, rs in groups.items()}, default=float)
    )

    def mean(rs: list[dict[str, Any]], key: str, *path: str) -> float:
        vals = []
        for r in rs:
            x: Any = r["results"][key]
            for p in path:
                x = x[p]
            vals.append(float(x))
        return float(np.mean(vals))

    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True
    ).stdout.strip()
    L = [
        "# Test-set results",
        "",
        f"Generated by `scripts/benchmark/evaluate.py` at commit `{commit}`. Mean over seeds. "
        "kcal MAE ↓, r ↑, F1 ±1 ↑, ECE ↓, cov 80 → 0.80.",
        "",
        "| run | seeds | "
        + " | ".join(f"{n} kcal MAE | r | F1 ±1 | ECE | cov 80" for n in SETS.values())
        + " |",
        "|---|---|" + "---|" * (5 * len(SETS)),
    ]
    for g, rs in groups.items():
        cells = []
        for k in SETS:
            cells += [
                f"{mean(rs, k, 'kcal', 'point', 'mae'):.1f}",
                f"{mean(rs, k, 'kcal', 'point', 'pearson_r'):.3f}",
                f"{mean(rs, k, 'summary', 'macro_f1_pm1'):.2f}",
                f"{mean(rs, k, 'summary', 'ece'):.3f}",
                f"{mean(rs, k, 'summary', 'coverage_80'):.2f}",
            ]
        L.append(f"| {g} | {len(rs)} | " + " | ".join(cells) + " |")
    args.out.write_text("\n".join(L) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
